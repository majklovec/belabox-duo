// REFACTOR-modules.md §4.1 — build-time generated module manifests.
//
// Emits two manifests, one static import per module (sorted for deterministic
// output), default-exporting the registrations as an array. Each file lists
// paths only — it never imports a module — so a broken module cannot break
// the generator:
//
//   modules/.generated.frontend.ts — one import per modules/<id>/frontend.tsx;
//   the browser bundle statically resolves every import (no runtime Glob).
//   modules/.generated.backend.ts  — one import per modules/<id>/backend.ts;
//   used by the compiled binaries (bun build --compile), where the runtime
//   directory scan in src/registry.ts cannot reach disk (import.meta.url
//   lives in Bun's virtual /$bunfs mount).
//
// Runs in Bun (not the browser) and is re-invoked by server.ts before it
// bundles the web UI, plus by package.json `predev`/`pretest` and the release
// workflow before the compiled builds. Regenerated on demand; only rewrites a
// file when the output actually changes so watch loops don't churn it.
import { fileURLToPath } from "node:url";
import { writeFile, readFile } from "node:fs/promises";
import { sep } from "node:path";

// scripts/ lives next to modules/ — the app dir is the scan base so the
// relative patterns below resolve the same way regardless of the CWD.
const baseDir = fileURLToPath(new URL("..", import.meta.url));

interface ManifestSpec {
	outFile: string; // fileURLToPath'ed output path
	pattern: string; // e.g. modules/*/frontend.tsx
	variable: string; // import base name, e.g. m / b
	importSuffix: string; // e.g. frontend / backend
	purpose: string; // header line describing the manifest
}

async function buildManifest(spec: ManifestSpec): Promise<void> {
	const matches: string[] = [];
	for await (const p of new Bun.Glob(spec.pattern).scan({ cwd: baseDir })) matches.push(p);
	matches.sort();

	const lines = [
		"// AUTO-GENERATED by scripts/gen-modules.ts — do not edit.",
		`// ${spec.purpose}`,
		"// One static import per matching module, in sorted path order.",
		"",
	];

	matches.forEach((path, i) => {
		// path = <modulesDir>/<id>/frontend.tsx  →  import "./<id>/frontend"
		const parts = path.split(sep);
		const moduleId = parts[parts.length - 2];
		lines.push(`import ${spec.variable}${i} from "./${moduleId}/${spec.importSuffix}";`);
	});

	lines.push("");
	lines.push(
		matches.length
			? `export default [${[...Array(matches.length)].map((_, i) => `${spec.variable}${i}`).join(", ")}] as unknown[];`
			: "export default [] as unknown[];",
		"",
	);

	const next = lines.join("\n");
	let prev = "";
	try {
		prev = await readFile(spec.outFile, "utf8");
	} catch {
		/* missing — will write */
	}
	if (next !== prev) await writeFile(spec.outFile, next);
	console.log(`[gen-modules] ${spec.outFile.split(sep).pop()} → ${matches.length} ${spec.importSuffix} module(s)`);
}

await Promise.all([
	buildManifest({
		outFile: fileURLToPath(new URL("../modules/.generated.frontend.ts", import.meta.url)),
		pattern: "modules/*/frontend.tsx",
		variable: "m",
		importSuffix: "frontend",
		purpose: "REFACTOR-modules.md §4.1: one static import per modules/<id>/frontend.tsx; the browser bundle never uses Glob",
	}),
	buildManifest({
		outFile: fileURLToPath(new URL("../modules/.generated.backend.ts", import.meta.url)),
		pattern: "modules/*/backend.ts",
		variable: "b",
		importSuffix: "backend",
		purpose: "one static import per modules/<id>/backend.ts for the compiled binaries (bun build --compile), where the runtime scan cannot reach disk",
	}),
]);
